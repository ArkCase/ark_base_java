import java.io.ByteArrayOutputStream;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Collections;
import java.util.Comparator;
import java.util.Map;
import java.util.Properties;
import java.util.Set;
import java.util.TreeSet;

/**
 * usage: java PropertiesXml.java (to-xml | from-xml) INPUT OUTPUT
 *
 * Converts a properties file (such as java.security) to the XML format of java.util.Properties, and back.
 * Both directions use the JDK's own parser and writer (Properties.load/storeToXML and loadFromXML/store),
 * so the result is read exactly as the JDK reads java.security, whatever syntax the file uses (line
 * continuations, escapes, ':' or '=' separators, ...). The entries are written sorted by key, so the
 * output is stable. Comments are not kept.
 *
 * Files that use the "include" directive (Java 24+) are refused: its effect depends on where it appears
 * in the file, and on how many times, which a set of properties can't represent.
 *
 * Exits with 0 on success, 1 on incorrect usage, and 2 if the file can't be converted.
 */
public class PropertiesXml {

	private static final String HEADER = "Generated by fips-java-security from the JDK's own file (comments removed)";

	// Iterates in key order, so store() and storeToXML() write sorted output
	private static class SortedProperties extends Properties {
		private static final long serialVersionUID = 1L;

		@Override
		public Set<Map.Entry<Object, Object>> entrySet() {
			Set<Map.Entry<Object, Object>> sorted = new TreeSet<>(Comparator.comparing((Map.Entry<Object, Object> e) -> e.getKey().toString()));
			sorted.addAll(super.entrySet());
			return Collections.unmodifiableSet(sorted);
		}
	}

	public static void main(String[] args) throws Exception {
		if (args.length != 3) {
			System.err.println("usage: java PropertiesXml.java (to-xml | from-xml) INPUT OUTPUT");
			System.exit(1);
		}

		Properties props = new SortedProperties();
		Path input = Path.of(args[1]);
		Path output = Path.of(args[2]);
		switch (args[0]) {
			case "to-xml":
				// ISO-8859-1, which is what the JDK uses for java.security
				try (InputStream in = Files.newInputStream(input)) {
					props.load(in);
				}
				if (props.containsKey("include")) {
					System.err.println("The file [" + input + "] uses the \"include\" directive, which can't be converted");
					System.exit(2);
				}
				try (OutputStream out = Files.newOutputStream(output)) {
					props.storeToXML(out, HEADER, StandardCharsets.UTF_8);
				}
				break;

			case "from-xml":
				try (InputStream in = Files.newInputStream(input)) {
					props.loadFromXML(in);
				}
				// store() adds a timestamp comment after the header: leave it out, so the output is stable
				ByteArrayOutputStream buf = new ByteArrayOutputStream();
				props.store(buf, HEADER);
				String text = buf.toString(StandardCharsets.ISO_8859_1);
				int first = text.indexOf('\n');
				int second = text.indexOf('\n', first + 1);
				text = text.substring(0, first + 1) + text.substring(second + 1);
				Files.write(output, text.getBytes(StandardCharsets.ISO_8859_1));
				break;

			default:
				System.err.println("usage: java PropertiesXml.java (to-xml | from-xml) INPUT OUTPUT");
				System.exit(1);
		}
	}
}
